/**
 * 玩家脚盒（设计 px）。
 *
 * 只覆盖**双脚落地那一小块**，不覆盖整个立绘：俯视 2.5D 里上半身本来就该挡住床沿/墙，
 * 但拿整个立绘宽度去判碰撞会让角色卡在窄过道里。
 *
 * - 宽 56：能穿过 3 格宽的缝（tileSize≈21.8 → 65px）；旧的 88 宽在这条缝里几乎站不进去。
 * - 高 18：鞋帮高度。
 * - `padding: 8`：**视觉间余**。没有它时脚底探针正好压在障碍格边界上，
 *   角色能贴着床沿站，实机上看着就是「脚踩在床框上」。外扩 8px 让脚与床/墙之间留出一条看得见的缝（4px 在手机上只有 2 个 CSS 像素，看着仍像踩上去）。
 */
export const PLAYER_FOOT: FootBox = { width: 56, height: 18, padding: 8 };

